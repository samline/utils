/** The icon markup a feature names; an unknown name fails the build instead of rendering blank. */
export const featureIcon = (name: string, feature: string) => {
  if (!Object.hasOwn(featureIcons, name))
    throw new Error(
      `Feature "${feature}" names an unknown icon "${name}". Use one of: ${Object.keys(featureIcons).join(', ')}`
    )
  return featureIcons[name as FeatureIcon]
}
